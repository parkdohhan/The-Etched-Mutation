import path from 'node:path';

const SUPABASE_URL = 'https://bxmppaxpzbkwebfbgpsm.supabase.co';
const SUPABASE_ANON_KEY = 'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6ImJ4bXBwYXhwemJrd2ViZmJncHNtIiwicm9sZSI6ImFub24iLCJpYXQiOjE3NjUwMTcyMTEsImV4cCI6MjA4MDU5MzIxMX0.vv6Bmi2rZdx_HzLcxuw1wxfN_fvQYiigQz11KPNxH2M';
const FN_URL = `${SUPABASE_URL}/functions/v1/claude-scene`;
const CONCURRENCY = 3;
const GAP_MS = 300;

function arg(name, fallback) {
  const i = process.argv.indexOf('--' + name);
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}
const specPath = arg('spec', null);
const memoryId = arg('memory-id', null);
const outPath = arg('out', null);
const dry = process.argv.includes('--dry');
if (!specPath || !memoryId) { console.error('usage: --spec <spec.json> --memory-id <uuid> [--out pool.sql] [--dry]'); process.exit(1); }

const spec = JSON.parse(fs.readFileSync(path.resolve(specPath), 'utf8'));
const pool = Array.isArray(spec.drift_pool) ? spec.drift_pool : [];
if (!pool.length) { console.error('drift_pool 이 비어 있다'); process.exit(1); }

async function extractOnce(text) {
  const resp = await fetch(FN_URL, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', apikey: SUPABASE_ANON_KEY, Authorization: `Bearer ${SUPABASE_ANON_KEY}` },
    body: JSON.stringify({ type: 'emotion_extract', user_text: text, scene_text: '' }),
  });
  if (!resp.ok) throw new Error(`HTTP ${resp.status}`);
  const data = await resp.json();
  const base = data && data.base && typeof data.base === 'object' ? data.base : null;
  if (!base) throw new Error('base 없음');
  return { vec: base, version: String(data.prompt_version || 'unknown') };
}
async function extract(text) {
  for (let attempt = 0; attempt < 3; attempt++) {
    try { return await extractOnce(text); }
    catch (e) { process.stderr.write(`retry(${attempt + 1}): ${e.message}\n`); await new Promise((r) => setTimeout(r, 1500)); }
  }
  return { vec: {}, version: 'extract-failed' };
}

function dq(s) { let tag = 'q', n = 0; while (s.includes('$' + tag + '$')) { n += 1; tag = 'q' + n; } return '$' + tag + '$' + s + '$' + tag + '$'; }
function textArr(arr) { const xs = Array.isArray(arr) ? arr : []; return xs.length ? 'ARRAY[' + xs.map((x) => dq(String(x))).join(', ') + ']::text[]' : "'{}'::text[]"; }

async function main() {
  const results = new Array(pool.length);
  if (!dry) {
    let cursor = 0, done = 0;
    async function worker() {
      while (cursor < pool.length) {
        const i = cursor++;
        results[i] = await extract(pool[i].utterance);
        done += 1;
        if (done % 5 === 0 || done === pool.length) console.error(`  ${done}/${pool.length}`);
        await new Promise((r) => setTimeout(r, GAP_MS));
      }
    }
    await Promise.all(Array.from({ length: CONCURRENCY }, worker));
  }
  const rows = pool.map((p, i) => {
    const r = results[i] || { vec: {}, version: 'dry' };
    // anchor:true = 작가 본 발화 (is_seed=true, parent 없음). lumen_dialog_phase1 의 연결사 풀(ldp pool)이
    // 이 한 줄을 기준으로 나머지를 공명/모호/불협으로 나눈다 — 없으면 "글로벌 디폴트 유지" 경고. 기억당 1개.
    return '(' + [
      dq(memoryId) + '::uuid', "'drift'", p.anchor ? 'true' : 'false', 'NULL',
      dq(String(p.utterance)),
      textArr(p.motif_tags),
      dq(JSON.stringify(r.vec)) + '::jsonb',
      dq(r.version + '+author_pool'),
    ].join(', ') + ')';
  });
  const sql = '-- generated by tools/author_memory_drift_pool.mjs — ' + path.basename(specPath) + ' → memory ' + memoryId + '\n' +
    'insert into ghost_variants (memory_id, kind, is_seed, parent_variant_id, utterance, motif_tags, emotion_vec, extractor_version)\nvalues\n' +
    rows.join(',\n') + '\nreturning id, left(utterance, 20) as head;\n';
  if (outPath) { fs.writeFileSync(path.resolve(outPath), sql, 'utf8'); console.error('wrote ' + outPath + ' (' + rows.length + ' rows)'); }
  else process.stdout.write(sql);
}
main().catch((e) => { console.error(e); process.exit(1); });
