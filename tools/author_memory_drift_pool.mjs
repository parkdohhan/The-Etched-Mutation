// 유령 재료(작가가 화자 목소리로 쓴 문장들)를 ghost_variants(kind=drift) 로 심기 위한 SQL 을 만든다.
// 대표 기억(UNDW-001)과 같은 결: is_seed=false(대화 재료 + 사물 열람 변주 둘 다 소비되게),
// emotion_vec 는 claude-scene emotion_extract(12축, temperature 0)로 자동 측정,
// extractor_version = 응답 prompt_version + '+author_pool'.
//
// 사용:
//   node tools/author_memory_drift_pool.mjs --spec <spec.json> --memory-id <uuid> --out pool.sql
//   (--dry : 측정 없이 emotion_vec={} 로 SQL 만)
//
// 이 파일은 DB 에 쓰지 않는다 — anon 키는 ghost_variants INSERT 가 RLS 로 막히므로
// service_role / SQL 편집기 / MCP 로 실행한다.

