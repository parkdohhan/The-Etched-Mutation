//
// 기억의 씬 중 meta.sound_prompt 는 있고 meta.sound_url 은 없는 씬마다
// generate-scene-sound(mode=generate: ElevenLabs SFX 18초 → Storage scene_sounds → public URL) 를 부르고,
// 결과를 meta.sound_url 로 심는 UPDATE 문을 만든다. 볼륨·반경은 이미 meta 에 있는 값을 그대로 둔다.
//
// 사용:
//   node tools/author_memory_sounds.mjs --memory-id <uuid> --out sounds.sql
//   --dry : 생성 없이 대상 씬만 나열
//   --only 1,3,7 : scene_order 필터
//
// DB 쓰기는 하지 않는다 (anon 은 scenes UPDATE 가 RLS 로 0행). SQL 을 service_role/편집기/MCP 로 실행.

import fs from 'node:fs';
import path from 'node:path';

const SUPABASE_URL = 'https://bxmppaxpzbkwebfbgpsm.supabase.co';
const SUPABASE_ANON_KEY = 'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6ImJ4bXBwYXhwemJrd2ViZmJncHNtIiwicm9sZSI6ImFub24iLCJpYXQiOjE3NjUwMTcyMTEsImV4cCI6MjA4MDU5MzIxMX0.vv6Bmi2rZdx_HzLcxuw1wxfN_fvQYiigQz11KPNxH2M';
const FN_URL = `${SUPABASE_URL}/functions/v1/generate-scene-sound`;
const CONCURRENCY = 2;   // ElevenLabs 동시 생성 제한 보수적으로
const GAP_MS = 800;

function arg(name, fallback) {
  const i = process.argv.indexOf('--' + name);
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}
const memoryId = arg('memory-id', null);
const outPath = arg('out', null);
const only = (arg('only', '') || '').split(',').map((s) => Number(s)).filter((n) => Number.isFinite(n) && n > 0);
const dry = process.argv.includes('--dry');
if (!memoryId) { console.error('usage: --memory-id <uuid> [--out sounds.sql] [--dry] [--only 1,2]'); process.exit(1); }

async function fetchScenes() {
  const resp = await fetch(`${SUPABASE_URL}/rest/v1/scenes?memory_id=eq.${memoryId}&select=id,scene_order,meta&order=scene_order`,
    { headers: { apikey: SUPABASE_ANON_KEY, Authorization: `Bearer ${SUPABASE_ANON_KEY}` } });
  if (!resp.ok) throw new Error(`scenes fetch HTTP ${resp.status}`);
  return resp.json();
}
async function generate(sceneId, prompt) {
  const resp = await fetch(FN_URL, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', apikey: SUPABASE_ANON_KEY, Authorization: `Bearer ${SUPABASE_ANON_KEY}` },
    body: JSON.stringify({ mode: 'generate', prompt, sceneId }),
  });
  const data = await resp.json().catch(() => ({}));
  if (!resp.ok || !data.soundUrl) throw new Error(`HTTP ${resp.status} ${JSON.stringify(data).slice(0, 300)}`);
  return data.soundUrl;
}
function dq(s) { let tag = 'q', n = 0; while (s.includes('$' + tag + '$')) { n += 1; tag = 'q' + n; } return '$' + tag + '$' + s + '$' + tag + '$'; }

async function main() {
  const scenes = await fetchScenes();
  const targets = scenes.filter((s) => {
    const m = s.meta || {};
    if (only.length && !only.includes(s.scene_order)) return false;
    return !!(m.sound_prompt && String(m.sound_prompt).trim()) && !m.sound_url;
  });
  console.error(`씬 ${scenes.length}개 중 생성 대상 ${targets.length}개`);
  targets.forEach((s) => console.error(`  #${s.scene_order} ${s.id.slice(0, 8)}… "${String(s.meta.sound_prompt).slice(0, 60)}"`));
  if (dry) return;

  const results = [];
  let cursor = 0;
  async function worker() {
    while (cursor < targets.length) {
      const s = targets[cursor++];
      let url = null, err = null;
      for (let attempt = 0; attempt < 2 && !url; attempt++) {
        try { url = await generate(s.id, s.meta.sound_prompt); }
        catch (e) { err = e.message; process.stderr.write(`  #${s.scene_order} 실패(${attempt + 1}): ${e.message}\n`); await new Promise((r) => setTimeout(r, 2500)); }
      }
      results.push({ id: s.id, order: s.scene_order, url, err });
      if (url) console.error(`  #${s.scene_order} ✓ ${url.slice(-40)}`);
      await new Promise((r) => setTimeout(r, GAP_MS));
    }
  }
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));

  const ok = results.filter((r) => r.url).sort((a, b) => a.order - b.order);
  const sql = '-- generated by tools/author_memory_sounds.mjs — memory ' + memoryId + '\n' +
    ok.map((r) => `update scenes set meta = meta || jsonb_build_object('sound_url', ${dq(r.url)}) where id = ${dq(r.id)}::uuid; -- #${r.order}`).join('\n') + '\n';
  if (outPath) { fs.writeFileSync(path.resolve(outPath), sql, 'utf8'); console.error('wrote ' + outPath + ' (' + ok.length + ' updates, ' + (results.length - ok.length) + ' failed)'); }
  else process.stdout.write(sql);
  const failed = results.filter((r) => !r.url);
  if (failed.length) console.error('실패: ' + failed.map((r) => '#' + r.order + ' ' + r.err).join(' | '));
}
main().catch((e) => { console.error(e); process.exit(1); });
